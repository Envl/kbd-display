#!/bin/bash
set -euo pipefail
cd "$(dirname "$0")/.."
command -v cwebp >/dev/null || { echo "Install cwebp to bake web blades." >&2; exit 1; }
atlas_tmp=$(mktemp -d)
trap 'rm -rf "$atlas_tmp"' EXIT
# Render native frames at half resolution into one transparent atlas per blade.
cat Sources/KbdDisplay/BladeStyle.swift Sources/KbdDisplay/BladeTrailRenderer.swift - <<'SWIFT' | xcrun swift -target "$(uname -m)-apple-macos13.0" - "$atlas_tmp"
import ImageIO
import UniformTypeIdentifiers

let output = URL(fileURLWithPath: FileManager.default.currentDirectoryPath).appendingPathComponent("web")
let directory = output.appendingPathComponent("art/blades")
try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
let bounds = BladeTrailRenderer.bounds
let frames = BladeTrailRenderer.frames, columns = 4, rows = (frames + columns - 1) / columns
let scale = 0.5, cellWidth = Int(bounds.width * scale), cellHeight = Int(bounds.height * scale)
for style in BladeStyle.allCases {
    let bitmap = CGContext(data: nil, width: columns * cellWidth, height: rows * cellHeight,
                           bitsPerComponent: 8, bytesPerRow: 0, space: CGColorSpace(name: CGColorSpace.sRGB)!,
                           bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue)!
    for i in 0..<frames {
        bitmap.saveGState()
        bitmap.translateBy(x: CGFloat(i % columns * cellWidth), y: CGFloat((rows - 1 - i / columns) * cellHeight))
        bitmap.scaleBy(x: scale, y: scale)
        bitmap.translateBy(x: -bounds.minX, y: -bounds.minY)
        BladeTrailRenderer.draw(style, from: .zero, to: CGPoint(x: 480, y: 0), thickness: 10,
                                elapsed: (Double(i) + 0.5) / Double(frames) * style.trailLifetime,
                                opacity: 1, seed: 0, in: bitmap)
        bitmap.restoreGState()
    }
    let url = URL(fileURLWithPath: CommandLine.arguments[1]).appendingPathComponent("\(style.rawValue).png")
    let destination = CGImageDestinationCreateWithURL(url as CFURL, UTType.png.identifier as CFString, 1, nil)!
    CGImageDestinationAddImage(destination, bitmap.makeImage()!, nil)
    precondition(CGImageDestinationFinalize(destination), "Failed to write \(url)")
}
let durations = BladeStyle.allCases.map { String($0.trailLifetime) }.joined(separator: ", ")
let js = """
// Generated by scripts/bake-web-blades.sh from the native blade renderer.
export const bladeDurations = [\(durations)];
export const atlas = { frames: \(frames), columns: \(columns), cellWidth: \(cellWidth), cellHeight: \(cellHeight),
  x: \(Int(bounds.minX)), y: \(Int(bounds.minY)), width: \(Int(bounds.width)), height: \(Int(bounds.height)), span: 480 };

"""
try js.write(to: output.appendingPathComponent("blade-atlas.js"), atomically: true, encoding: .utf8)
SWIFT
for png in "$atlas_tmp"/*.png; do
    name=$(basename "$png" .png)
    cwebp -quiet -lossless "$png" -o "$atlas_tmp/$name.webp"
    mv "$atlas_tmp/$name.webp" "web/art/blades/$name.webp"
done
